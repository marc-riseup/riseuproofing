/**
 * Generates the sky horizon silhouettes (San Diego rooftops + palms, 3 depth layers) as static SVGs
 * in public/img/sky/. They are used as CSS masks by components/sky/Sky.tsx, so the path data is not
 * inlined into the HTML / RSC payload. Run: node scripts/gen-horizon.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';

/* ---------- San Diego rooftop + palm silhouette, 3 depth layers (deterministic vector) ---------- */
const W = 2400;
const H = 120;

function rng(seed) {
  return () => {
    seed = (seed * 1664525 + 1013904223) >>> 0;
    return seed / 4294967296;
  };
}

/** One palm: tapered, gently curved trunk + drooping fronds, as closed leaf shapes. */
function palm(x, base, h, lean) {
  const top = base - h;
  const tx = x + lean;
  const w0 = Math.max(2.2, h * 0.035);
  const w1 = w0 * 0.55;
  // trunk (quadratic bow)
  let d = `M${x - w0} ${base}Q${x + lean * 0.35 - w0} ${base - h * 0.55} ${tx - w1} ${top}L${tx + w1} ${top}Q${x + lean * 0.35 + w0} ${base - h * 0.55} ${x + w0} ${base}Z`;
  // fronds: 6 leaves, angles in degrees from straight up (negative = left)
  const fr = h * 0.36;
  for (const a of [-112, -72, -32, 30, 70, 110]) {
    const rad = (a * Math.PI) / 180;
    const len = fr * (Math.abs(a) > 100 ? 0.84 : 1);
    const ex = tx + Math.sin(rad) * len;
    const ey = top - Math.cos(rad) * len * 0.55 + Math.abs(Math.sin(rad)) * len * 0.42; // droop
    const mx = tx + Math.sin(rad) * len * 0.5;
    const my = top - Math.cos(rad) * len * 0.7 - 4;
    const t = Math.max(1.6, len * 0.09);
    d += `M${tx} ${top}Q${mx - t * Math.cos(rad)} ${my - t} ${ex} ${ey}Q${mx + t * Math.cos(rad)} ${my + t} ${tx} ${top + 1.5}Z`;
  }
  return d;
}

/** A row of houses (gable / hip / two-story) with a few palms, from a seed. */
function row(seed, base, scale, palmEvery) {
  const r = rng(seed);
  let x = -40;
  let d = `M-40 ${H}V${base}`;
  const palms = [];
  let n = 0;
  while (x < W + 40) {
    const w = (90 + r() * 120) * scale;
    const wallH = (14 + r() * 16) * scale * (r() < 0.22 ? 1.7 : 1); // some two-story
    const roofH = (10 + r() * 14) * scale;
    const wall = base - wallH;
    const peak = wall - roofH;
    const kind = r();
    d += `H${x}V${wall}`;
    if (kind < 0.45) {
      // gable
      d += `L${x + w / 2} ${peak}L${x + w} ${wall}`;
    } else if (kind < 0.85) {
      // hip (flat ridge)
      const inset = w * (0.24 + r() * 0.1);
      d += `L${x + inset} ${peak}H${x + w - inset}L${x + w} ${wall}`;
    } else {
      // low flat-roof with parapet
      d += `V${wall - 4 * scale}H${x + w}V${wall}`;
    }
    d += `V${base}`;
    n += 1;
    if (n % palmEvery === 0) palms.push(palm(x + w * (0.2 + r() * 0.6), base, (52 + r() * 40) * scale, (r() - 0.5) * 16 * scale));
    x += w + (r() < 0.3 ? 8 * scale : 0);
  }
  d += `H${W + 40}V${H}Z`;
  return [d, ...palms].join('');
}

const BACK = row(7, H - 30, 0.62, 3);
const MID = row(23, H - 14, 0.82, 4);
const FRONT = row(41, H, 1, 5);

const round = (d) =>
  d
    .replace(/-?\d+\.\d+/g, (n) => String(Math.round(+n)))
    .replace(/\s+([MLQHVZ])/g, '$1')
    .replace(/([MLQHVZ])\s+/g, '$1');
mkdirSync('public/img/sky', { recursive: true });
const paths = {};
for (const [name, d] of Object.entries({ back: BACK, mid: MID, front: FRONT })) {
  const rd = round(d);
  paths[name] = rd;
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${W} ${H}'><path d='${rd}'/></svg>`;
  writeFileSync(`public/img/sky/horizon-${name}.svg`, svg);
  console.log(name, rd.length, 'bytes');
}
writeFileSync(
  'components/sky/horizon-paths.ts',
  `// Generated by scripts/gen-horizon.mjs\nexport const HORIZON_PATHS = ${JSON.stringify(paths, null, 2)} as const;\n`,
);
