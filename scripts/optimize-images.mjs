// Builds every raster the homepage uses into /public/img as AVIF + WebP.
// Source = the 2.0 asset folder (content reference only). Re-run after swapping real photos:
//   npm run images
import sharp from 'sharp';
import { mkdir, copyFile, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const SRC = path.resolve(root, '../Riseup 2.0');
const OUT = path.join(root, 'public/img');

const A = (p) => path.join(SRC, 'public/assets', p);
const S = (p) => path.join(SRC, 'screenshots/sections', p);

async function ensure(dir) {
  await mkdir(dir, { recursive: true });
}

/** Write AVIF + WebP at each width. */
async function variants(src, outBase, widths, { crop, alpha = false, quality = 62 } = {}) {
  await ensure(path.dirname(outBase));
  for (const w of widths) {
    let img = sharp(src);
    if (crop) img = img.extract(crop);
    img = img.resize({ width: w, withoutEnlargement: false, kernel: 'lanczos3' });
    const suffix = widths.length > 1 ? `-${w}` : '';
    await img.clone().avif({ quality: quality - 12, effort: 5 }).toFile(`${outBase}${suffix}.avif`);
    await img.clone().webp({ quality, alphaQuality: alpha ? 90 : 100, effort: 5 }).toFile(`${outBase}${suffix}.webp`);
  }
}

